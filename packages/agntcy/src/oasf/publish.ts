// Real client against the AGNTCY Directory, using the real, published
// `agntcy-dir` npm package (https://www.npmjs.com/package/agntcy-dir,
// TypeScript SDK, gRPC via ConnectRPC). An earlier version of this file
// claimed no such package existed — that was wrong; the original check only
// guessed scoped names like `@agntcy/dir` and got 404s. The real package is
// unscoped (`agntcy-dir`). Verified live against a local Directory server
// (Go apiserver + zot OCI registry + postgres, built and run from
// github.com/agntcy/dir's own `install/docker/docker-compose.yml`) — a real
// record was pushed and published against it during development of this file.
//
// TAXONOMY MAPPING (previously the one deliberately-unmapped gap, now real):
// `src/oasf/taxonomy.generated.json` ships all 364 genuine leaf skills from a
// real checkout of github.com/agntcy/oasf's `schema/skills/**`, generated by
// `scripts/generate-oasf-taxonomy.mjs` (re-run that script against a fresh
// checkout to pick up upstream taxonomy changes). `KNOWN_AGENT_SKILLS` below
// maps this repo's REAL internal capability vocabulary — the exact ids
// `harness-genome`'s `plan.agents`/`plan.skills`/`genome.agent_topology`
// actually emit (see `project.ts`'s `projectToOasf`) — onto that generated
// data; every id below is asserted to exist in the generated table by this
// file's own test suite, so a stale/renamed upstream id fails a test rather
// than silently mis-tagging every published record.
//
// Composite id derivation (`category*10000 + subcategory*100 + leaf`):
// reverse-engineered from agntcy/dir-sdk-javascript's own example.js (two
// worked examples) and confirmed structurally against every category/
// subcategory/leaf JSON's own `uid` field. One real ambiguity this
// implementation resolves correctly: a file that shares its own subcategory
// directory's name (e.g. `code_generation/code_generation.json`) is the
// SUBCATEGORY's own definition (`extends` points at the CATEGORY) — not a
// leaf under itself — and must be excluded from the leaf table, or every
// composite id built from it would silently collide with the taxonomy's real
// leaf uid=1 under that subcategory. `generate-oasf-taxonomy.mjs` excludes it;
// an earlier draft of this file's own comments described a wrong "self-node,
// leaf defaults to 1" theory before this was traced through the real
// `agntcy/oasf` tree.
//
// RESOLVED (agntcy/dir#1943 — root cause found by upstream maintainer
// @akijakya, 2026-07-31): every earlier "name is broken" / "id is broken"
// finding in this file's history was actually the SAME self-inflicted bug —
// the pushed record's `schema_version` field was hardcoded to `'0.8.0'`
// while `taxonomy.generated.json`'s ids/names come from OASF **1.1.0**'s
// `schema/skills/**` tree. The live server validates a skill's `id`/`name`
// against the taxonomy for the record's OWN declared `schema_version`, so
// every 1.1.0-derived id/name was being checked against the 0.8.0 taxonomy
// and correctly rejected — id=60101 only "worked" by coincidence (0.8.0
// happens to have an unrelated skill, "indexing", at that same numeric
// slot). Fixed below by declaring `schema_version: '1.1.0'` to match the
// taxonomy this file actually uses. Verified live: all 9 previously-"broken"
// ids now push successfully, and sending BOTH `id` and the taxonomy's own
// dotted `name` together (self-documenting, not id-only) also now works.

import { Client, Config } from 'agntcy-dir';
import { create } from '@bufbuild/protobuf';
import { RecordRefsSchema, PublishRequestSchema } from '@buf/agntcy_dir.bufbuild_es/agntcy/dir/routing/v1/routing_service_pb.js';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import type { OasfRecord } from './record.js';

// Read as a runtime asset rather than a static JSON import — avoids
// requiring `resolveJsonModule` + JSON import-attribute support (Node
// >=20.10 only) across the whole package just for this one generated file,
// and keeps `taxonomy.generated.json` a plain build asset the "build" script
// copies alongside the compiled .js (see package.json), rather than
// something tsc needs to understand.
const taxonomyPath = fileURLToPath(new URL('./taxonomy.generated.json', import.meta.url));
const taxonomy: unknown = JSON.parse(readFileSync(taxonomyPath, 'utf8'));

export interface PublishResult {
  published: boolean;
  reason?: string;
  /** The Directory's content-addressed reference for the pushed record, when published. */
  ref?: unknown;
}

export interface PublishTarget {
  /** Harness name — not tracked by OasfRecord itself; the caller (whoever
   * knows the harness's package name) supplies it rather than this function
   * inventing one. */
  name: string;
  version: string;
  /** Defaults to AGNTCY_DIRECTORY_ENDPOINT, then DIRECTORY_CLIENT_SERVER_ADDRESS
   * (the agntcy-dir SDK's own env var), then undefined (fails closed). */
  serverAddress?: string;
  /**
   * A pre-configured SDK `Config` — set `config.authMode` to `'tls'`, `'x509'`,
   * or `'jwt'` (plus the matching `tls*`/`jwtAudience`/`spiffeEndpointSocket`
   * fields) to authenticate for real against a production Directory instead
   * of the SDK's insecure plaintext default. When omitted, this function
   * builds one via `Config.loadFromEnv()`, so any `DIRECTORY_CLIENT_AUTH_MODE`
   * / `DIRECTORY_CLIENT_TLS_*` / `DIRECTORY_CLIENT_JWT_AUDIENCE` environment
   * variables already set (the SDK's own documented convention — see its
   * README's "Configuration" section) take effect automatically. `authMode:
   * 'oidc'` is not supported through this path: it requires an interactive
   * PKCE login this synchronous publish call has no way to drive — pass a
   * `Config` with a pre-cached `authToken` instead if OIDC is your auth mode.
   */
  config?: Config;
}

interface TaxonomyLeaf {
  id: number;
  path: string;
  caption: string;
  description: string;
}

export const TAXONOMY: TaxonomyLeaf[] = taxonomy as TaxonomyLeaf[];
const TAXONOMY_IDS = new Set(TAXONOMY.map((leaf) => leaf.id));

/** Assert-and-look-up: throws at import time (loud, not a silent typo) if a
 * path below no longer exists in the generated taxonomy — e.g. after
 * re-running generate-oasf-taxonomy.mjs against a renamed/removed upstream
 * leaf. Prefer this over hand-copying numeric ids. */
function leafId(path: string): number {
  const leaf = TAXONOMY.find((l) => l.path === path);
  if (!leaf) {
    throw new Error(
      `oasf/publish.ts: taxonomy leaf "${path}" not found in taxonomy.generated.json — ` +
        `re-run scripts/generate-oasf-taxonomy.mjs against a current agntcy/oasf checkout, ` +
        `then fix or remove this mapping if the leaf was renamed/removed upstream.`,
    );
  }
  return leaf.id;
}

/** `{ id, name }` pair for a taxonomy path — sending both together is the
 * self-documenting form confirmed to work live (see the RESOLVED note
 * above); `name` is exactly the leaf's own dotted path, nothing derived. */
function skillOf(path: string): { id: number; name: string } {
  return { id: leafId(path), name: path };
}

