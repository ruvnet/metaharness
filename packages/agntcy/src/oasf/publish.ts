function projectSkills(record: OasfRecord): Array<{ id: number; name: string }> {
  // The real Directory server requires a non-empty skills array (validated
  // live — see this file's test suite). Map every capability with a known
  // real taxonomy entry, sending both `id` and the taxonomy's own dotted
  // `name` together (self-documenting; confirmed live to work once
  // schema_version matches — see the RESOLVED note above). Anything
  // unrecognized gets the closest honest category-level fallback rather
  // than being silently dropped, since the array cannot be empty.
  if (record.capabilities.length === 0) return [FALLBACK_SKILL];
  const seen = new Set<number>();
  const skills: Array<{ id: number; name: string }> = [];
  for (const cap of record.capabilities) {
    const mapped = KNOWN_AGENT_SKILLS[cap.id] ?? FALLBACK_SKILL;
    if (!seen.has(mapped.id)) {
      seen.add(mapped.id);
      skills.push(mapped);
    }
  }
  return skills;
}

function projectAnnotations(record: OasfRecord): Record<string, string> {
  const annotations: Record<string, string> = {};
  for (const cap of record.capabilities) annotations[`capability.${cap.kind}.${cap.id}`] = 'true';
  for (const proto of record.supportedProtocols) annotations[`host.${proto.host}`] = 'true';
  annotations['model.recommendedMode'] = record.modelRequirements.recommendedMode;
  annotations['model.estCostPerRunUsd'] = String(record.modelRequirements.estCostPerRunUsd);
  annotations['resource.mcpEnabled'] = String(record.resourceEnvelope.mcpEnabled);
  annotations['resource.shellAccess'] = String(record.resourceEnvelope.shellAccess);
  annotations['resource.networkAccess'] = String(record.resourceEnvelope.networkAccess);
  annotations['resource.fileWriteAccess'] = String(record.resourceEnvelope.fileWriteAccess);
  for (const scope of record.securityScopes) annotations[`security.${scope.severity}.${scope.id}`] = scope.title;
  for (const ev of record.evaluationHistory) annotations[`evaluation.${ev.source}.${ev.metric}`] = String(ev.value);
  // pricingMeteringClass intentionally never appears here — projectToOasf (project.ts)
  // never populates it (fails closed, see record.ts's file header), so there is
  // nothing to project.
  return annotations;
}

/** Rebuild a Config with a different serverAddress by re-running the real
 * constructor (see the call site's comment for why a plain property
 * assignment is wrong here) — every other field carries over unchanged. */
function withServerAddress(config: Config, serverAddress: string): Config {
  return new Config(
    serverAddress,
    config.dirctlPath,
    config.spiffeEndpointSocket,
    config.authMode,
    config.jwtAudience,
    config.tlsCaFile,
    config.tlsCertFile,
    config.tlsKeyFile,
    config.authToken,
    config.tlsServerName,
    config.tlsSkipVerify,
    config.oidcIssuer,
    config.oidcClientId,
    config.oidcClientSecret,
    config.oidcRedirectUri,
    config.oidcCallbackPort,
    config.oidcAuthTimeout,
    config.oidcScopes,
    config.oidcAccessToken,
    config.dockerConfig,
  );
}

/**
 * Push an OasfRecord to a real AGNTCY Directory server and publish it to the
 * routing table (making it discoverable). Fails closed with a clear reason
 * when no server is configured or the call fails — never a silent no-op,
 * never a faked success.
 */
export async function publishToDirectory(record: OasfRecord, target: PublishTarget): Promise<PublishResult> {
  if (record.schema !== 1) {
    return { published: false, reason: 'invalid OasfRecord: unsupported schema version' };
  }

  // Fail-closed server resolution stays independent of the SDK's own
  // Config.loadFromEnv() default (127.0.0.1:8888) — loadFromEnv() ALWAYS
  // returns a non-empty serverAddress, which would silently attempt a real
  // network call to localhost even when the caller configured nothing.
  const serverAddress = target.serverAddress ?? process.env.AGNTCY_DIRECTORY_ENDPOINT ?? process.env.DIRECTORY_CLIENT_SERVER_ADDRESS;
  if (!serverAddress) {
    return {
      published: false,
      reason: 'No Directory server configured — set AGNTCY_DIRECTORY_ENDPOINT (or the SDK\'s own DIRECTORY_CLIENT_SERVER_ADDRESS) to a real server address.',
    };
  }

  // SECURITY: real TLS/x509/JWT auth, not the insecure default. `target.config`
  // (explicit) wins; otherwise Config.loadFromEnv() picks up the SDK's own
  // DIRECTORY_CLIENT_AUTH_MODE/TLS_*/JWT_AUDIENCE/SPIFFE_SOCKET_PATH env vars,
  // so a deployment that exports those gets real authentication automatically
  // — this function no longer forces `authMode: ''` (plaintext, no auth) the
  // way an earlier version did. Config.createGRPCTransport() (below) already
  // implements the real tls/x509/jwt transport construction for every mode
  // this accepts; this file only needed to stop discarding the caller's
  // configuration, not reimplement transport security itself.
  //
  // withServerAddress() re-runs the Config CONSTRUCTOR rather than assigning
  // `.serverAddress` on an already-built instance — the constructor is where
  // the SDK normalizes a bare `host:port` into a full URL (`http://` for
  // plaintext, `https://` for tls/x509/jwt/oidc); a plain property assignment
  // skips that entirely and the transport layer then throws `Invalid URL` on
  // the un-prefixed address (caught by this file's own live-server test).
  const loaded = target.config ?? Config.loadFromEnv();
  const config = withServerAddress(loaded, serverAddress);
  if (config.authMode === 'oidc') {
    return {
      published: false,
      reason: 'authMode "oidc" requires an interactive PKCE login this non-interactive publish call cannot drive — pass a Config with a pre-cached authToken instead.',
    };
  }

  const dirRecord = {
    data: {
      name: target.name,
      version: target.version,
      // Must match the OASF version taxonomy.generated.json was derived
      // from (1.1.0) — see the RESOLVED note at the top of this file. A
      // stale schema_version here is what caused every earlier "id/name is
      // broken" finding: the server validates skills against the taxonomy
      // for the record's OWN declared version, not whatever version the
      // caller had in mind.
      schema_version: '1.1.0',
      description: 'MetaHarness-generated harness (ADR-240 §2.2 projection)',
      authors: ['metaharness'],
      created_at: record.generatedAt,
      skills: projectSkills(record),
      // Real locator `type` enum is unspecified|helm_chart|container_image|
      // package|source_code|binary|url (github.com/agntcy/oasf schema/objects/
      // locator.json) — describes artifact download locations, not runtime
      // hosts. This repo's deploymentOptions.hosts (e.g. "claude-code") isn't
      // an artifact locator in that sense, so it stays out of locators (which
      // the live server validates whenever present) and goes into
      // annotations instead, alongside every other capability we track.
      locators: [] as unknown[],
      domains: [] as unknown[],
      annotations: projectAnnotations(record),
      modules: [] as unknown[],
    },
  };

  try {
    const transport = await Client.createGRPCTransport(config);
    const client = new Client(config, transport);
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    const pushedRefs = await client.push([dirRecord as any]);
    if (pushedRefs.length === 0) {
      return { published: false, reason: 'Directory push returned no record reference' };
    }
    await client.publish(
      create(PublishRequestSchema, { request: { case: 'recordRefs', value: create(RecordRefsSchema, { refs: pushedRefs }) } }),
    );
    return { published: true, ref: pushedRefs[0] };
  } catch (err) {
    return { published: false, reason: `Directory push/publish failed: ${err instanceof Error ? err.message : String(err)}` };
  }
}

/** Exported for this file's own tests — asserts every KNOWN_AGENT_SKILLS
 * entry's id genuinely exists in the generated taxonomy (leafId() already
 * throws at import time on a miss; this re-check exists so a test failure
 * names the exact file, not a module-load crash). */
export function __allMappedIdsExistInTaxonomy(): boolean {
  return Object.values(KNOWN_AGENT_SKILLS).every((v) => TAXONOMY_IDS.has(v.id)) && TAXONOMY_IDS.has(FALLBACK_SKILL.id);
}
